# T-005: 日付形式方言の正規化。パース不能は空文字(例外にしない)
import pytest

from src.dates import normalize_date

pytestmark = pytest.mark.unit


@pytest.mark.parametrize(
    "raw,expected",
    [
        ("Wed, 19 Aug 2026 10:00:00 +0900", "2026-08-19"),
        ("Wed, 19 Aug 2026 10:00:00 GMT", "2026-08-19"),
        ("2026-08-19T10:00:00+09:00", "2026-08-19"),
        ("2026-08-19T01:00:00Z", "2026-08-19"),
        ("2026-08-19", "2026-08-19"),
        ("2026年8月19日", "2026-08-19"),
        ("2026年12月3日", "2026-12-03"),
        ("2026.8.19", "2026-08-19"),
        ("2026.12.03", "2026-12-03"),
        ("2026/08/19", "2026-08-19"),
        ("  2026年8月19日 発表 ", "2026-08-19"),
        ("", ""),
        ("日付なし", ""),
        (None, ""),
    ],
)
def test_normalize_date(raw, expected):
    assert normalize_date(raw) == expected
